#!/usr/bin/env python3
"""Index public Codex source candidates at the pinned commit; no runtime inspection."""
import pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'references/codex'
REV = '3d86e43b075adeba2193ec5c22ac92f55afd82e6'
URL = f'https://github.com/openai/codex/blob/{REV}/'

def git(*args):
    return subprocess.check_output(['git', '-C', str(SOURCE), *args], text=True)

entries = git('ls-tree', '-r', REV).splitlines()
files = []
for line in entries:
    meta, name = line.split('\t', 1)
    blob = meta.split()[2]
    if not name.startswith('codex-rs/') or not name.endswith(('.md', '.rs', '.lark')):
        continue
    prompt = (name.startswith('codex-rs/prompts/') or
              (name.endswith('.md') and re.search(r'prompt|instruction|template', name, re.I)))
    tools = (re.search(r'(^|/)(tools|tool[^/]*)(/|\.rs$)', name) or
             re.search(r'(tool|function).*(spec|registry|schema).*\.rs$', name))
    if prompt or tools:
        files.append((name, blob, bool(prompt), bool(tools)))

out = ['# Codex public source index', '', f'Pinned commit: `{REV}` (`rust-v0.172.0`). Generated by `python3 codex/generate-public-index.py`; `--check` compares without writing.', '',
       'This is an inclusive, path-based source inventory, not a list of active runtime tools. It includes tests and helper modules to avoid silently excluding conditional registrations; candidates may not themselves be model-facing. Inline strings outside these path rules and remote model-catalog content remain gaps. Links and Git blob IDs pin the exact public source. Inspect builders, feature gates, model and platform branches before attributing a definition to a session.', '']
for title, flag in [('Prompt templates and assembly candidates', 2), ('Tool definitions, registration and helper candidates', 3)]:
    selected = [e for e in files if e[flag]]
    out += [f'## {title} ({len(selected)})', '', '| Public source path | Git blob |', '| --- | --- |']
    out += [f'| [`{name}`]({URL}{name}) | `{blob}` |' for name, blob, *_ in selected]
    out.append('')
content = '\n'.join(out)
matches = git('grep', '-n', '-E', r'(pub(\([^)]*\))? (const|fn) [A-Za-z0-9_]*(TOOL_NAME|[Tt]ool|_tool)|name: "[a-z][a-z0-9_]*")', REV, '--', 'codex-rs').splitlines()
hits = []
for match in matches:
    m = re.match(r'^[^:]+:([^:]+):(\d+):(.*)$', match)
    if m and m.group(1).endswith('.rs') and ('/tools/' in m.group(1) or '/tool' in m.group(1)) and not re.search(r'test|fixture|snapshot', m.group(1)):
        source, number, text = m.groups()
        hits.append((source, number, text.strip()))
out += ['## Declaration and constructor matches', '', 'Mechanical matches, not a definitive registration list: constants, constructors, and names can be aliases, helpers, optional, or disabled. Follow each link and its call sites to determine conditions. Dynamic and differently written declarations may be absent.', '', '| Source | Matching line |', '| --- | --- |']
for source, number, line in hits:
    safe = line.replace('|', '&#124;').replace('`', "'")
    out.append(f'| [`{source}:{number}`]({URL}{source}#L{number}) | `{safe}` |')
out.append('')
content = '\n'.join(out)
path = ROOT / 'codex/PUBLIC-SOURCE-INDEX.md'
if '--check' in sys.argv:
    if not path.exists() or path.read_text() != content:
        sys.exit('Public source index differs; regenerate it')
    print(f'Public source index matches {len(files)} source paths at {REV}')
else:
    path.write_text(content)
    print(f'Indexed {len(files)} source paths at {REV}')
